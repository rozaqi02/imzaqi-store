  where order_code ~ '^IMZ-[A-HJ-NP-Z2-9]{8,10}$';
create unique index if not exists orders_payment_reference_unique on public.orders(payment_reference)
  where payment_reference is not null and payment_reference <> 'FREE';
create index if not exists orders_reservation_expiry_idx on public.orders(reservation_expires_at)
  where status = 'pending_payment';

create table if not exists public.funnel_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  session_id uuid not null,
  event_name text not null check (event_name in (
    'view_product','select_variant','add_to_cart','buy_now','begin_checkout',
    'apply_promo','qris_opened','payment_reported','order_completed','restock_request'
  )),
  path text,
  product_id uuid,
  variant_id uuid,
  order_code text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists funnel_events_created_idx on public.funnel_events(created_at desc);
create index if not exists funnel_events_session_idx on public.funnel_events(session_id, created_at);

create table if not exists public.restock_requests (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  product_id uuid references public.products(id) on delete cascade,
  variant_id uuid references public.product_variants(id) on delete cascade,
  customer_whatsapp text not null,
  created_at timestamptz not null default now(),
  notified_at timestamptz,
  unique(visitor_id, variant_id)
);

create table if not exists public.status_lookup_attempts (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  attempted_at timestamptz not null default now()
);
create index if not exists status_lookup_attempts_rate_idx
  on public.status_lookup_attempts(visitor_id, attempted_at desc);
alter table public.status_lookup_attempts enable row level security;

alter table public.funnel_events enable row level security;
alter table public.restock_requests enable row level security;

drop policy if exists "anon insert funnel events" on public.funnel_events;
